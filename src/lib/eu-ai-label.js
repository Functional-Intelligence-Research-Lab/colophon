/**
 * eu-ai-label.js — Map a Colophon session onto the EU's AI-disclosure icons.
 *
 * Source of the icons and the rules they encode:
 *   https://digital-strategy.ec.europa.eu/en/policies/eu-icons-labelling-ai-generated-content
 *
 * The Commission publishes three marks (each in black/white × solid/50%-
 * transparent). Their meanings, and how a Colophon process log maps onto them:
 *
 *   'ai'         — the basic mark. AI was involved somewhere in producing the
 *                  content, without asserting how much. Our safe default when
 *                  AI was used but we can't justify a stronger claim.
 *   'ai-generated' — the content is *fully* AI-generated, i.e. no human-authored
 *                  material beyond the prompt.
 *   'ai-modified'  — pre-existing human-written content was *partially* altered
 *                  using AI.
 *
 * IMPORTANT — what this function is and isn't:
 *   This returns a SUGGESTION for the author, computed from what Colophon
 *   observed. It is not a legal determination. Article 50 disclosure duties
 *   attach to particular content types (deepfakes; public-interest text without
 *   human editorial review) and carry exemptions (artistic/satirical works,
 *   law enforcement). Colophon cannot know whether a given document falls in
 *   scope — only the author can. So the UI must present this as "suggested
 *   label", always overridable, never auto-applied.
 *
 * Licensing: the Commission makes these icons freely usable by anyone, with no
 * attribution required. Code of Practice signatories must additionally follow
 * the official placement specification.
 */

/** The three EU label kinds, plus 'none' when no AI was recorded. */
export const EU_LABEL = {
  NONE: 'none',
  AI: 'ai',
  AI_GENERATED: 'ai-generated',
  AI_MODIFIED: 'ai-modified',
}

/**
 * Fraction of kept AI characters at or above which we suggest "AI GENERATED".
 *
 * The Commission's guidance defines this mark as content "fully generated by AI
 * with no human-created elements or human editorial control (apart from
 * prompting)" — i.e. effectively 100% AI. We therefore set this very high
 * rather than at a loose "mostly AI" level: suggesting "fully AI generated" for
 * a document a human partly wrote would be a false disclosure, and the correct
 * mark in that case is AI MODIFIED. The small tolerance below 1.0 absorbs
 * measurement noise (whitespace, counting drift), not real human authorship.
 */
export const FULLY_AI_THRESHOLD = 0.995

/**
 * Below this fraction of AI characters we don't claim "modified" — a stray
 * accepted phrase in an otherwise human document gets the neutral basic mark.
 */
export const MODIFIED_MIN_THRESHOLD = 0.02

/**
 * Decide which EU icon a session suggests.
 *
 * @param {object} stats
 * @param {number} stats.humanChars  characters attributable to the author
 * @param {number} stats.aiChars     AI characters retained in the document
 * @returns {{label: string, reason: string, aiShare: number}}
 */
export function classifyEuLabel({ humanChars = 0, aiChars = 0 } = {}) {
  const total = humanChars + aiChars
  if (total <= 0 || aiChars <= 0) {
    return { label: EU_LABEL.NONE, reason: 'No AI contribution recorded.', aiShare: 0 }
  }

  const aiShare = aiChars / total

  if (aiShare >= FULLY_AI_THRESHOLD) {
    return {
      label: EU_LABEL.AI_GENERATED,
      reason: 'Effectively all recorded content came from AI output.',
      aiShare,
    }
  }

  if (aiShare >= MODIFIED_MIN_THRESHOLD) {
    return {
      label: EU_LABEL.AI_MODIFIED,
      reason: 'Human-written content was partially produced or altered using AI.',
      aiShare,
    }
  }

  return {
    label: EU_LABEL.AI,
    reason: 'AI was used, but its contribution to the final text is minimal.',
    aiShare,
  }
}

/**
 * Derive {humanChars, aiChars} from a session's event list.
 *
 * AI characters count only what was actually KEPT: rejected suggestions
 * contribute nothing, and where a similarity_score is available (how much of
 * the AI's wording survived the author's edits) we scale by it rather than
 * crediting the AI with text the author rewrote.
 */
export function summariseSession(events = []) {
  let humanChars = 0
  let aiChars = 0

  for (const e of events) {
    const m = e?.meta ?? {}
    if (e?.type === 'edit') {
      // Only human-sourced edits count toward authored characters.
      if ((m.source ?? 'human') === 'human') {
        humanChars += Math.max(0, m.char_delta ?? 0)
      }
    } else if (e?.type === 'ai_interaction' || e?.type === 'ai_suggestion') {
      if (m.acceptance === 'rejected') continue
      const kept = m.ai_chars ?? 0
      if (kept <= 0) continue
      // similarity_score (0-1) tells us how much of the AI wording survived.
      const survived = typeof m.similarity_score === 'number'
        ? Math.max(0, Math.min(1, m.similarity_score))
        : 1
      aiChars += kept * survived
    }
  }

  return { humanChars: Math.round(humanChars), aiChars: Math.round(aiChars) }
}

/** Convenience: classify straight from an event list. */
export function classifySessionEvents(events = []) {
  return classifyEuLabel(summariseSession(events))
}

/**
 * Asset path for a label, resolved against the packaged EU icon set.
 *
 * @param {string} label   one of EU_LABEL
 * @param {object} [opts]
 * @param {'black'|'white'} [opts.colour='black']
 * @param {boolean} [opts.transparent=false]  use the 50%-transparency variant
 * @returns {string|null} extension-relative path, or null for EU_LABEL.NONE
 */
export function euIconPath(label, { colour = 'black', transparent = false } = {}) {
  if (!label || label === EU_LABEL.NONE) return null
  const suffix = transparent ? `${colour}-transparent` : colour
  return `assets/eu-icons/${label}-${suffix}.svg`
}

/**
 * Human-readable label text — used for alt text / plain-language labelling,
 * which the Commission explicitly encourages for accessibility.
 */
export function euLabelText(label) {
  switch (label) {
    case EU_LABEL.AI_GENERATED: return 'AI generated'
    case EU_LABEL.AI_MODIFIED:  return 'AI modified'
    case EU_LABEL.AI:           return 'AI'
    default:                    return ''
  }
}
